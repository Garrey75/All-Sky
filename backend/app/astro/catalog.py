def _mk(rows: list[tuple]) -> list[SkyObject]:
    seen: set[str] = set()
    out: list[SkyObject] = []
    for row in rows:
        obj = SkyObject(*row)
        if obj.id in seen:
            continue
        seen.add(obj.id)
        out.append(obj)
    return out


CATALOG: list[SkyObject] = _mk(_MESSIER + _NGC + _STARS)


def get_object(oid: str) -> SkyObject | None:
    key = oid.strip().lower()
    for obj in CATALOG:
        if obj.id.lower() == key or obj.name.lower() == key or obj.name_zh == oid:
            return obj
    return None


def search_objects(query: str, limit: int = 40) -> list[SkyObject]:
    q = query.strip().lower()
    if not q:
        return [o for o in CATALOG if o.kind != "Star"][:limit]
    hits: list[SkyObject] = []
    for obj in CATALOG:
        blob = f"{obj.id} {obj.name} {obj.name_zh} {obj.constellation}".lower()
        if q in blob:
            hits.append(obj)
        if len(hits) >= limit:
            break
    return hits


def tonight_best(lat: float, lon: float, dt, min_alt: float = 30.0, limit: int = 16) -> list[dict]:
    scored: list[tuple[float, SkyObject, float]] = []
    for obj in CATALOG:
        if obj.kind == "Star":
            continue
        alt, az = altaz(obj.ra_hours, obj.dec_deg, lat, lon, dt)
        if alt < min_alt:
            continue
        score = alt - obj.mag * 2.0 + min(20.0, obj.size_arcmin / 4.0)
        scored.append((score, obj, alt))
    scored.sort(key=lambda x: x[0], reverse=True)
    out = []
    for score, obj, alt in scored[:limit]:
        out.append(
            {
                "id": obj.id,
                "name": obj.name,
                "name_zh": obj.name_zh,
                "ra_hours": obj.ra_hours,
                "dec_deg": obj.dec_deg,
                "mag": obj.mag,
                "size_arcmin": obj.size_arcmin,
                "kind": obj.kind,
                "alt": round(alt, 1),
                "score": round(score, 1),
            }
        )
    return out


